/**
 * `as const` keeps the Persian source readable and literal, but the English
 * dictionary must be structurally identical with *different* strings — so the
 * exported type widens every literal back to `string`.
 */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer Item)[]
        ? readonly Widen<Item>[]
        : { readonly [Key in keyof T]: Widen<T[Key]> };

export type Dictionary = Widen<typeof fa>;
